from datetime import datetime
from uuid import UUID, uuid4

from sqlalchemy import (
    Boolean,
    CheckConstraint,
    DateTime,
    ForeignKey,
    Index,
    Integer,
    String,
    UniqueConstraint,
    func,
    text,
)
from sqlalchemy.dialects.postgresql import UUID as PGUUID
from sqlalchemy.orm import Mapped, mapped_column

from app.db.base import Base


class AgentTestRun(Base):
    """Metadata for one local test-runner execution; no output is persisted."""

    __tablename__ = "agent_test_runs"

    __table_args__ = (
        UniqueConstraint(
            "execution_id",
            name="uq_agent_test_runs_execution_id",
        ),
        CheckConstraint(
            "runner IN ('pytest', 'npm', 'go')",
            name="ck_agent_test_runs_runner",
        ),
        CheckConstraint(
            "status IN ('passed', 'failed', 'timed_out', 'error')",
            name="ck_agent_test_runs_status",
        ),
        CheckConstraint(
            "duration_ms >= 0",
            name="ck_agent_test_runs_duration_ms",
        ),
        Index(
            "ix_agent_test_runs_user_created_at",
            "user_id",
            "created_at",
        ),
        Index(
            "ix_agent_test_runs_thread_created_at",
            "thread_id",
            "created_at",
        ),
        Index(
            "ix_agent_test_runs_status_created_at",
            "status",
            "created_at",
        ),
    )

    id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True),
        primary_key=True,
        default=uuid4,
        server_default=text("gen_random_uuid()"),
    )

    # ID generated by app.services.test_execution.runner.execute_tests().
    execution_id: Mapped[UUID] = mapped_column(
        PGUUID(as_uuid=True),
        nullable=False,
    )

    user_id: Mapped[UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True,
    )

    # Nullable for standalone test-execution API calls outside an agent workflow.
    thread_id: Mapped[UUID | None] = mapped_column(
        PGUUID(as_uuid=True),
        ForeignKey("agent_workflows.thread_id", ondelete="SET NULL"),
        nullable=True,
    )

    runner: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
    )

    status: Mapped[str] = mapped_column(
        String(16),
        nullable=False,
    )

    exit_code: Mapped[int | None] = mapped_column(
        Integer,
        nullable=True,
    )

    duration_ms: Mapped[int] = mapped_column(
        Integer,
        nullable=False,
    )

    stdout_truncated: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        server_default=text("false"),
    )

    stderr_truncated: Mapped[bool] = mapped_column(
        Boolean,
        nullable=False,
        default=False,
        server_default=text("false"),
    )

    started_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    finished_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
    )

    created_at: Mapped[datetime] = mapped_column(
        DateTime(timezone=True),
        nullable=False,
        server_default=func.now(),
    )