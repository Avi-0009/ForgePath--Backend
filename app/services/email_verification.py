
import hashlib
import hmac
import logging
import re
import secrets

from datetime import datetime, timedelta, timezone
from uuid import UUID

from sqlalchemy import select
from sqlalchemy.exc import IntegrityError
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.config import settings
from app.models.email_verification_otp import EmailVerificationOTP
from app.repositories import user as user_repository
from app.services.brevo_email import (
    BrevoEmailError,
    send_email_verification_otp,
)


logger = logging.getLogger(__name__)

OTP_LENGTH = 6
OTP_RESEND_COOLDOWN_SECONDS = 60


class EmailVerificationError(Exception):
    """Base exception for email-verification failures."""


class EmailAlreadyVerifiedError(EmailVerificationError):
    """The account's email has already been verified."""


class EmailVerificationRateLimitedError(EmailVerificationError):
    """An OTP was requested too recently."""


class EmailVerificationUserError(EmailVerificationError):
    """The account is unavailable for email verification."""


def _generate_otp() -> str:
    """Generate a cryptographically secure six-digit OTP."""
    return f"{secrets.randbelow(10 ** OTP_LENGTH):0{OTP_LENGTH}d}"


def _hash_otp(otp: str) -> str:
    """Create an HMAC-SHA256 hash of the OTP."""
    secret = settings.password_reset_secret_key.get_secret_value()

    return hmac.new(
        secret.encode("utf-8"),
        otp.encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()


async def _get_otp_record(
    db: AsyncSession,
    user_id: UUID,
    *,
    for_update: bool = False,
) -> EmailVerificationOTP | None:
    statement = select(EmailVerificationOTP).where(
        EmailVerificationOTP.user_id == user_id
    )

    if for_update:
        statement = statement.with_for_update()

    result = await db.execute(statement)
    return result.scalar_one_or_none()


async def request_email_verification_otp(
    db: AsyncSession,
    user_id: UUID,
) -> None:
    """
    Generate and email a verification OTP for the authenticated user.

    OTP persistence happens before email delivery. If delivery fails,
    the newly issued OTP is invalidated where possible.
    """
    user = await user_repository.get_by_id(db, user_id)

    if user is None or not user.is_active:
        await db.rollback()
        raise EmailVerificationUserError(
            "The account is unavailable for email verification."
        )

    if user.is_email_verified:
        await db.rollback()
        raise EmailAlreadyVerifiedError(
            "This email address has already been verified."
        )

    now = datetime.now(timezone.utc)

    try:
        record = await _get_otp_record(
            db,
            user.id,
            for_update=True,
        )

        if record is not None and record.created_at is not None:
            last_request = record.created_at

            # PostgreSQL returns timezone-aware timestamps.
            if last_request.tzinfo is None:
                last_request = last_request.replace(tzinfo=timezone.utc)

            if (
                now - last_request
                < timedelta(seconds=OTP_RESEND_COOLDOWN_SECONDS)
            ):
                await db.rollback()
                raise EmailVerificationRateLimitedError(
                    "Please wait before requesting another verification code."
                )

        otp = _generate_otp()
        otp_hash = _hash_otp(otp)
        expires_at = now + timedelta(
            minutes=settings.password_reset_otp_expire_minutes
        )

        if record is None:
            record = EmailVerificationOTP(
                user_id=user.id,
                otp_hash=otp_hash,
                expires_at=expires_at,
                attempts=0,
                created_at=now,
            )
            db.add(record)
        else:
            record.otp_hash = otp_hash
            record.expires_at = expires_at
            record.attempts = 0
            record.created_at = now
            record.used_at = None

        await db.commit()

    except EmailVerificationError:
        raise

    except IntegrityError as exc:
        await db.rollback()
        raise EmailVerificationRateLimitedError(
            "A verification request is already being processed. "
            "Please try again shortly."
        ) from exc

    except Exception:
        await db.rollback()
        raise

    # Send only after the OTP has been committed.
    try:
        await send_email_verification_otp(
            recipient_email=user.email,
            otp=otp,
        )

    except BrevoEmailError:
        # Invalidate only the OTP generated by this request.
        try:
            current_record = await _get_otp_record(
                db,
                user.id,
                for_update=True,
            )

            if (
                current_record is not None
                and hmac.compare_digest(
                    current_record.otp_hash,
                    otp_hash,
                )
                and current_record.used_at is None
            ):
                current_record.used_at = datetime.now(timezone.utc)
                await db.commit()
            else:
                await db.rollback()

        except Exception:
            await db.rollback()
            logger.exception(
                "Could not invalidate an OTP after email delivery failed"
            )

        raise


async def verify_email_with_otp(
    db: AsyncSession,
    user_id: UUID,
    otp: str,
) -> bool:
    """
    Verify the authenticated user's email.

    Returns False for an invalid, expired, consumed, or exhausted OTP.
    On success, sets users.is_email_verified and consumes the OTP
    in the same database transaction.
    """
    if not re.fullmatch(r"[0-9]{6}", otp):
        return False

    user = await user_repository.get_by_id(db, user_id)

    if user is None or not user.is_active:
        await db.rollback()
        return False

    if user.is_email_verified:
        await db.rollback()
        return True

    try:
        record = await _get_otp_record(
            db,
            user.id,
            for_update=True,
        )

        now = datetime.now(timezone.utc)

        if record is None or record.used_at is not None:
            await db.rollback()
            return False

        expires_at = record.expires_at
        if expires_at.tzinfo is None:
            expires_at = expires_at.replace(tzinfo=timezone.utc)

        if (
            expires_at <= now
            or record.attempts >= settings.password_reset_otp_max_attempts
        ):
            if record.used_at is None:
                record.used_at = now
                await db.commit()
            else:
                await db.rollback()

            return False

        submitted_hash = _hash_otp(otp)

        if not hmac.compare_digest(record.otp_hash, submitted_hash):
            record.attempts += 1

            if (
                record.attempts
                >= settings.password_reset_otp_max_attempts
            ):
                record.used_at = now

            await db.commit()
            return False

        # Verification and OTP consumption happen atomically.
        user.is_email_verified = True
        record.used_at = now

        await db.commit()
        return True

    except Exception:
        await db.rollback()
        raise
